const std = @import("std");
const helpers = @import("helpers.zig");
const pkcs12 = @import("jsz").pkcs12;

fn readPfx(allocator: std.mem.Allocator) ![]u8 {
    return readFixture(allocator, "https/pfx.p12");
}

fn readFixture(allocator: std.mem.Allocator, name: []const u8) ![]u8 {
    const path = try std.fs.path.join(allocator, &.{ helpers.fixture_dir, name });
    defer allocator.free(path);
    return std.Io.Dir.cwd().readFileAlloc(
        std.testing.io,
        path,
        allocator,
        .limited(1 << 20),
    );
}

test "pkcs12 parses an encrypted pfx into pem" {
    const allocator = std.testing.allocator;

    const bytes = try readPfx(allocator);
    defer allocator.free(bytes);

    var bundle = try pkcs12.parse(allocator, bytes, "jsz");
    defer bundle.deinit(allocator);

    try std.testing.expectStringStartsWith(bundle.cert_pem, "-----BEGIN CERTIFICATE-----");
    try std.testing.expectStringEndsWith(bundle.cert_pem, "-----END CERTIFICATE-----\n");
    try std.testing.expectStringStartsWith(bundle.key_pem, "-----BEGIN PRIVATE KEY-----");
    try std.testing.expectStringEndsWith(bundle.key_pem, "-----END PRIVATE KEY-----\n");
}

test "pkcs12 parses legacy libressl pbe algorithms" {
    const allocator = std.testing.allocator;

    // Generated by LibreSSL 3.3.6's default `pkcs12 -export`: certificates
    // use pbeWithSHA1And40BitRC2-CBC and the key uses
    // pbeWithSHA1And3-KeyTripleDES-CBC.
    const bytes = try readFixture(allocator, "https/legacy.p12");
    defer allocator.free(bytes);

    var bundle = try pkcs12.parse(allocator, bytes, "jsz");
    defer bundle.deinit(allocator);

    try std.testing.expectStringStartsWith(bundle.cert_pem, "-----BEGIN CERTIFICATE-----");
    try std.testing.expectStringEndsWith(bundle.cert_pem, "-----END CERTIFICATE-----\n");
    try std.testing.expectStringStartsWith(bundle.key_pem, "-----BEGIN PRIVATE KEY-----");
    try std.testing.expectStringEndsWith(bundle.key_pem, "-----END PRIVATE KEY-----\n");

    // The PEM bodies must actually contain data, not just the markers.
    try std.testing.expect(bundle.cert_pem.len > 256);
    try std.testing.expect(bundle.key_pem.len > 256);
}

test "pkcs12 rejects malformed input" {
    try std.testing.expectError(
        error.InvalidPfx,
        pkcs12.parse(std.testing.allocator, "not a pfx", "jsz"),
    );
}

test "pkcs12 rejects the wrong passphrase" {
    const allocator = std.testing.allocator;

    const bytes = try readPfx(allocator);
    defer allocator.free(bytes);

    try std.testing.expectError(
        error.InvalidPassword,
        pkcs12.parse(allocator, bytes, "not-jsz"),
    );
}

test "pkcs12 rejects the wrong passphrase for legacy pbe" {
    const allocator = std.testing.allocator;

    const bytes = try readFixture(allocator, "https/legacy.p12");
    defer allocator.free(bytes);

    try std.testing.expectError(
        error.InvalidPassword,
        pkcs12.parse(allocator, bytes, "not-jsz"),
    );
}
